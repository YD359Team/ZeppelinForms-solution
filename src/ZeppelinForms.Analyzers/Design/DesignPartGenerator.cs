using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace ZeppelinForms.Analyzers.Design;

/// <summary>
/// What a hand-written design part gets, as a markup one does: a constructor that builds
/// it, when the class declares none, and Hot Reload — <c>InitializeComponent()</c> runs
/// again after an edit, so a change of the <c>.design.cs</c> shows in the running form.
/// </summary>
/// <remarks>
/// <para>
/// So <c>MainForm.cs</c> may be the behaviour alone: no constructor, only the handlers
/// <c>InitializeComponent</c> wires. A class that declares a constructor calls
/// <c>InitializeComponent()</c> in it itself — ZF0007 reminds when one doesn't.
/// </para>
/// <para>
/// The Hot Reload hook is left to the class when it overrides <c>OnHotReload</c> itself,
/// and to classes that are neither a form nor an element. A nested class gets neither:
/// a part of it would need parts of every class around it.
/// </para>
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class DesignPartGenerator : IIncrementalGenerator
{
    private const string FormMetadataName = "ZeppelinForms.Forms.Form";
    private const string ElementMetadataName = "ZeppelinForms.Forms.Controls.Base.UIElement";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<DesignedClass> classes = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) =>
                    node is MethodDeclarationSyntax { Identifier.ValueText: DesignParts.Method, ParameterList.Parameters.Count: 0 } &&
                    DesignParts.IsDesignFile(node.SyntaxTree.FilePath),
                static (syntax, cancel) => Describe(syntax, cancel))
            .Where(static described => described is not null)
            .Select(static (described, _) => described!)

            // a class with two design parts — two .design.cs — is written once; the
            // compiler reports the second InitializeComponent itself
            .Collect()
            .SelectMany(static (all, _) => all.Distinct());

        context.RegisterSourceOutput(classes, static (output, designed) =>
            output.AddSource(designed.HintName, SourceText.From(Emit(designed), Encoding.UTF8)));
    }

    private static DesignedClass? Describe(GeneratorSyntaxContext syntax, CancellationToken cancel)
    {
        if (syntax.SemanticModel.GetDeclaredSymbol(syntax.Node, cancel) is not IMethodSymbol { IsStatic: false } method)
            return null;

        INamedTypeSymbol type = method.ContainingType;

        if (type.TypeKind != TypeKind.Class || type.ContainingType is not null || type.IsStatic)
            return null;

        bool needsConstructor = type.InstanceConstructors.All(constructor => constructor.IsImplicitlyDeclared);

        bool reloads = (InheritsFrom(type, FormMetadataName) || InheritsFrom(type, ElementMetadataName)) &&
            !type.GetMembers("OnHotReload").Any(member => !member.IsImplicitlyDeclared);

        if (!needsConstructor && !reloads) return null;

        string ns = type.ContainingNamespace.IsGlobalNamespace ? string.Empty : type.ContainingNamespace.ToDisplayString();

        string typeParameters = type.TypeParameters.Length == 0
            ? string.Empty
            : "<" + string.Join(", ", type.TypeParameters.Select(parameter => parameter.Name)) + ">";

        string file = Path.GetFileName(syntax.Node.SyntaxTree.FilePath);

        return new DesignedClass(ns, type.Name, typeParameters, type.IsAbstract, needsConstructor, reloads, file);
    }

    private static bool InheritsFrom(INamedTypeSymbol type, string metadataName)
    {
        for (INamedTypeSymbol? current = type.BaseType; current is not null; current = current.BaseType)
        {
            if (current.ToDisplayString() == metadataName) return true;
        }

        return false;
    }

    private static string Emit(DesignedClass designed)
    {
        var source = new StringBuilder();

        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine("#pragma warning disable");
        source.AppendLine();

        if (designed.Namespace.Length > 0)
        {
            source.Append("namespace ").AppendLine(designed.Namespace);
            source.AppendLine("{");
        }

        source.Append("    partial class ").Append(designed.Name).AppendLine(designed.TypeParameters);
        source.AppendLine("    {");

        if (designed.NeedsConstructor)
        {
            source.Append("        /// <summary>Builds what ").Append(designed.File).AppendLine(" describes.</summary>");
            source.AppendLine("        [global::System.CodeDom.Compiler.GeneratedCode(\"ZeppelinForms.Analyzers\", null)]");
            source.Append(designed.IsAbstract ? "        protected " : "        public ").Append(designed.Name).AppendLine("()");
            source.AppendLine("        {");
            source.AppendLine("            InitializeComponent();");
            source.AppendLine("        }");
        }

        if (designed.Reloads)
        {
            if (designed.NeedsConstructor) source.AppendLine();

            source.Append("        /// <summary>Hot Reload: an edit of ").Append(designed.File)
                .AppendLine(" builds the design anew.</summary>");
            source.AppendLine("        [global::System.CodeDom.Compiler.GeneratedCode(\"ZeppelinForms.Analyzers\", null)]");
            source.AppendLine("        protected override void OnHotReload(global::ZeppelinForms.Forms.HotReloadEventArgs e)");
            source.AppendLine("        {");
            source.AppendLine("            base.OnHotReload(e);");
            source.Append("            if (e.Changed(typeof(").Append(designed.Name).Append(designed.TypeParameters)
                .AppendLine("))) InitializeComponent();");
            source.AppendLine("        }");
        }

        source.AppendLine("    }");

        if (designed.Namespace.Length > 0) source.AppendLine("}");

        return source.ToString();
    }

    /// <summary>What the generator needs of a class, comparable by value: the incremental
    /// pipeline writes again only what changed. Get-only properties, not a positional
    /// record: netstandard2.0 has no IsExternalInit for init accessors.</summary>
    private sealed record DesignedClass
    {
        public DesignedClass(
            string ns, string name, string typeParameters, bool isAbstract, bool needsConstructor, bool reloads, string file)
        {
            Namespace = ns;
            Name = name;
            TypeParameters = typeParameters;
            IsAbstract = isAbstract;
            NeedsConstructor = needsConstructor;
            Reloads = reloads;
            File = file;
        }

        public string Namespace { get; }

        public string Name { get; }

        /// <summary>"&lt;T, U&gt;", or empty.</summary>
        public string TypeParameters { get; }

        public bool IsAbstract { get; }

        public bool NeedsConstructor { get; }

        public bool Reloads { get; }

        /// <summary>The design part's file name, for the comments.</summary>
        public string File { get; }

        public string HintName =>
            (Namespace.Length > 0 ? Namespace + "." : string.Empty) + Name +
            (TypeParameters.Length > 0 ? "`" + (TypeParameters.Count(c => c == ',') + 1) : string.Empty) +
            ".design.g.cs";
    }
}
