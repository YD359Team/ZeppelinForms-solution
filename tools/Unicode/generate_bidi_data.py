"""Writes src/ZeppelinForms/Core/Text/BidiData.g.cs: the bidirectional class of every
code point, as ranges, for the bidi algorithm (UAX #9).

The classes come from Python's unicodedata, which carries the Unicode Character
Database of its version. Code points the database leaves unassigned get the defaults
DerivedBidiClass.txt gives them: R or AL in the blocks of right-to-left scripts, ET for
currency symbols, BN for noncharacters and default ignorables, L elsewhere.

Run with any Python 3 from the repository root:
    python3 tools/Unicode/generate_bidi_data.py
"""

import os
import unicodedata

CLASSES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS",
           "ON", "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]

# DerivedBidiClass.txt, @missing lines
DEFAULT_R = [(0x0590, 0x05FF), (0x07C0, 0x085F), (0xFB1D, 0xFB4F), (0x10800, 0x10CFF),
             (0x10D40, 0x10EBF), (0x10F00, 0x10F2F), (0x10F70, 0x10FFF), (0x1E800, 0x1EC6F),
             (0x1ECC0, 0x1ECFF), (0x1ED50, 0x1EDFF), (0x1EF00, 0x1EFFF)]
DEFAULT_AL = [(0x0600, 0x07BF), (0x0860, 0x08FF), (0xFB50, 0xFDCF), (0xFDF0, 0xFDFF),
              (0xFE70, 0xFEFF), (0x10D00, 0x10D3F), (0x10EC0, 0x10EFF), (0x10F30, 0x10F6F),
              (0x1EC70, 0x1ECBF), (0x1ED00, 0x1ED4F), (0x1EE00, 0x1EEFF)]
DEFAULT_ET = [(0x20A0, 0x20CF)]
DEFAULT_BN = [(0xFDD0, 0xFDEF), (0x2060, 0x206F), (0xFFF0, 0xFFF8), (0x1BCA0, 0x1BCAF),
              (0xE0000, 0xE0FFF)]


def default_class(cp):
    if (cp & 0xFFFE) == 0xFFFE:
        return "BN"
    for table, name in ((DEFAULT_BN, "BN"), (DEFAULT_R, "R"), (DEFAULT_AL, "AL"), (DEFAULT_ET, "ET")):
        for lo, hi in table:
            if lo <= cp <= hi:
                return name
    return "L"


def main():
    starts, classes = [], []
    previous = None

    for cp in range(0x110000):
        name = unicodedata.bidirectional(chr(cp)) or default_class(cp)

        if name != previous:
            starts.append(cp)
            classes.append(CLASSES.index(name))
            previous = name

    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    path = os.path.join(root, "src", "ZeppelinForms", "Core", "Text", "BidiData.g.cs")

    def rows(values, per_line):
        for i in range(0, len(values), per_line):
            yield "        " + ", ".join(values[i:i + per_line]) + ","

    with open(path, "w", encoding="utf-8-sig", newline="\n") as out:
        out.write("// <auto-generated/>\n")
        out.write(f"// Generated by tools/Unicode/generate_bidi_data.py from the Unicode Character\n")
        out.write(f"// Database {unicodedata.unidata_version}. Don't edit: run the script again.\n\n")
        out.write("namespace ZeppelinForms.Core.Text;\n\n")
        out.write("internal static partial class BidiData\n{\n")
        out.write(f"    /// <summary>Unicode {unicodedata.unidata_version}.</summary>\n")
        out.write(f"    public const string UnicodeVersion = \"{unicodedata.unidata_version}\";\n\n")
        out.write("    /// <summary>The first code point of each range.</summary>\n")
        out.write("    private static ReadOnlySpan<int> Starts =>\n    [\n")
        out.write("\n".join(rows([f"0x{s:X}" for s in starts], 10)))
        out.write("\n    ];\n\n")
        out.write("    /// <summary>The <see cref=\"BidiClass\"/> of each range.</summary>\n")
        out.write("    private static ReadOnlySpan<byte> Classes =>\n    [\n")
        out.write("\n".join(rows([str(c) for c in classes], 30)))
        out.write("\n    ];\n}\n")

    print(f"{len(starts)} ranges, Unicode {unicodedata.unidata_version} -> {path}")


if __name__ == "__main__":
    main()
